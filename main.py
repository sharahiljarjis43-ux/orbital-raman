"""Bennu OVIRS heterogeneity analysis — Plan A orchestrator.

Pipeline
--------
1. Parse the OSIRIS-REx Spectral Analysis Bundle 3.2-3.6 μm band-area FITS.
2. Apply photometric quality filter (band-area SNR ≥ 5).
3. Calibrate band area → wt% organic carbon (Kaplan/Praet, sample-anchored).
4. Classify facets as organic / carbonate / weak.
5. Validate against Ferrone et al. (2021) headline fractions (factor-of-2 gate).
6. Compute heterogeneity statistics (CDF, multi-pointing probability, Moran's I).
7. Re-run the Section 5 photon-budget Monte Carlo with empirical prior.
8. Produce fig_heterogeneity.{png,pdf} and write all markdown deliverables.

CLI
---
    python main.py --output-dir results/

The analysis is fully deterministic (numpy seed 42) and completes in a few
minutes on a laptop.
"""
